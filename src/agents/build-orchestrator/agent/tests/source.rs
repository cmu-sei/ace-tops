//! A build's source step (O3c) through the real protocols: a commit fetched by the git handler from a stand-in git server,
//! archived from the clone it brought up to date, and pushed by the HTTP handler to a stand-in registry (`common`); the build
//! is given the archive by its digest.

mod common;

use build_orchestrator::archive::archive;
use build_orchestrator::deps::{self, DOWNLOAD};
use build_orchestrator::lock::Crate;
use build_orchestrator::push::{PUSH, digest_of};
use build_orchestrator::settings::{CRATES_VAR, REGISTRY_VAR};
use build_orchestrator::source::{FETCH, FETCH_PUBLIC, GitSource, How, Source};
use common::{Crates, Registry, crates_host, registry};
use git2::{Repository, Signature, Time};
use orchestrator_core::types::{SourceRef, source_env};
use polar_agent_builder::protocol::OperationDecl;
use polar_agent_builder::protocol::testing::{GitOrigin, git_and_http_handle, git_ca};
use std::sync::Arc;
use wiremock::MockServer;

const OPERATIONS: &[OperationDecl] = &[FETCH, FETCH_PUBLIC, PUSH, DOWNLOAD];

struct Rig {
    _origin_dir: tempfile::TempDir,
    origin_repository: Repository,
    origin: GitOrigin,
    _dependency_dir: tempfile::TempDir,
    dependency_repository: Repository,
    _dependency: GitOrigin,
    dependency_commit: String,
    _clones: tempfile::TempDir,
    _registry_server: MockServer,
    registry: Registry,
    registry_url: String,
    _crates_server: MockServer,
    _crates: Crates,
    tiny: Crate,
    source: Arc<GitSource>,
    commit: String,
}

/// A bare repository whose main is one commit of `files`, served.
async fn repository(
    files: &[(&str, &[u8], i32)],
) -> (tempfile::TempDir, Repository, GitOrigin, String) {
    let dir = tempfile::tempdir().unwrap();
    let repository = Repository::init_bare(dir.path()).unwrap();
    let commit = {
        let mut tree = repository.treebuilder(None).unwrap();
        for (name, bytes, mode) in files {
            tree.insert(name, repository.blob(bytes).unwrap(), *mode)
                .unwrap();
        }
        let tree = repository.find_tree(tree.write().unwrap()).unwrap();
        let who =
            Signature::new("polar", "polar@example.org", &Time::new(1_800_000_000, 0)).unwrap();
        repository
            .commit(Some("refs/heads/main"), &who, &who, "first", &tree, &[])
            .unwrap()
            .to_string()
    };
    repository.set_head("refs/heads/main").unwrap();
    let origin = GitOrigin::serving(dir.path()).await;
    (dir, repository, origin, commit)
}

/// The lock a source's tree holds: its own package, a crate from the crates host, and a git dependency at its commit.
fn lock_of(tiny: &Crate, dependency_url: &str, dependency_commit: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n\
         [[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"dep\",\n \"tiny\",\n]\n\n\
         [[package]]\nname = \"dep\"\nversion = \"0.1.0\"\nsource = \"git+{dependency_url}#{dependency_commit}\"\n\n\
         [[package]]\nname = \"tiny\"\nversion = \"0.1.0\"\n\
         source = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"{}\"\n",
        tiny.sha256
    )
}

/// A repository with one commit on main, holding a lock that pins a crate and a git dependency, each served; a stand-in
/// registry and crates host; and the source step over them.
async fn rig() -> Rig {
    let (dependency_dir, dependency_repository, dependency, dependency_commit) =
        repository(&[("Cargo.toml", b"[package]\nname = \"dep\"\n", 0o100644)]).await;
    let dependency_url = dependency.url_over_tls().await;
    let (crates_server, crates) = crates_host().await;
    let tiny_bytes: &[u8] = b"tiny's crate";
    let tiny = Crate {
        name: "tiny".into(),
        version: "0.1.0".into(),
        sha256: digest_of(tiny_bytes)["sha256:".len()..].to_string(),
    };
    crates
        .0
        .lock()
        .unwrap()
        .files
        .insert(deps::crate_path(&tiny), tiny_bytes.to_vec());
    let lock = lock_of(&tiny, &dependency_url, &dependency_commit);
    let (dir, repository, origin, commit) = repository(&[
        ("README", b"a repository\n", 0o100644),
        ("build.sh", b"#!/bin/sh\n", 0o100755),
        ("Cargo.lock", lock.as_bytes(), 0o100644),
    ])
    .await;
    let (registry_server, registry) = registry().await;
    let registry_url = registry_server.uri();
    let site = git_and_http_handle(
        &git_ca().pem,
        OPERATIONS,
        vec![
            (REGISTRY_VAR, registry_url.clone()),
            (CRATES_VAR, crates_server.uri()),
        ],
        None,
    )
    .await;
    let clones = tempfile::tempdir().unwrap();
    let source = Arc::new(GitSource::new(
        site.handle,
        clones.path(),
        registry_url.clone(),
    ));
    Rig {
        _origin_dir: dir,
        origin_repository: repository,
        origin,
        _dependency_dir: dependency_dir,
        dependency_repository,
        _dependency: dependency,
        dependency_commit,
        _clones: clones,
        _registry_server: registry_server,
        registry,
        registry_url,
        _crates_server: crates_server,
        _crates: crates,
        tiny,
        source,
        commit,
    }
}

/// Fetched with no credential, its source at most `bound` bytes, and no locks.
fn public(bound: usize) -> How {
    How {
        credential: None,
        locks: vec![],
        max_source: bound,
        max_dependencies: u64::MAX,
    }
}

fn git(rig: &Rig, commit: &str) -> SourceRef {
    SourceRef::Git {
        url: rig.origin.url(),
        commit_sha: commit.to_string(),
    }
}

#[tokio::test]
async fn a_commit_is_fetched_archived_and_pushed_and_the_build_given_it_by_digest() {
    let rig = rig().await;
    let pinned = rig
        .source
        .prepare(&git(&rig, &rig.commit), &public(usize::MAX))
        .await
        .unwrap();
    // What the origin's own commit archives to: the same bytes, whatever clone they were read from.
    let expected = archive(&rig.origin_repository, &rig.commit, usize::MAX).unwrap();
    let digest = digest_of(&expected);
    let host = rig.registry_url.strip_prefix("http://").unwrap();
    assert_eq!(pinned.reference(), format!("{host}/build-sources@{digest}"));
    assert_eq!(pinned.sha256(), &digest["sha256:".len()..]);
    let held = rig.registry.0.lock().unwrap();
    assert_eq!(held.blobs.get(&digest), Some(&expected));
    assert!(
        held.manifests
            .contains_key(&format!("build-sources:{}", rig.commit)),
        "the manifest, by the commit"
    );
    // The registry is plain http, and the fetch is told so.
    assert!(pinned.fetch_env().contains(&(
        source_env::REGISTRY_INSECURE.to_string(),
        "true".to_string()
    )));
}

