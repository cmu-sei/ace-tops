/// Its lock read from the same commit, every dependency it pins brought into the registry by digest: the crate by the sha256
/// the lock pins, the git dependency archived at the commit it pins; and the build given the index of them.
#[tokio::test]
async fn a_sources_locked_dependencies_are_brought_into_the_registry_by_digest() {
    let rig = rig().await;
    let how = How {
        locks: vec!["Cargo.lock".into()],
        ..public(usize::MAX)
    };
    let pinned = rig
        .source
        .prepare(&git(&rig, &rig.commit), &how)
        .await
        .unwrap();
    let index_reference = pinned
        .dependencies()
        .expect("the index of its dependencies");
    let host = rig.registry_url.strip_prefix("http://").unwrap();
    assert!(
        index_reference.starts_with(&format!("{host}/build-dependencies@sha256:")),
        "{index_reference}"
    );
    let index_digest = index_reference.rsplit_once('@').unwrap().1;
    let dependency_archive = build_orchestrator::shallow::repository(
        &rig.dependency_repository,
        &rig.dependency_commit,
        usize::MAX,
    )
    .unwrap();
    let held = rig.registry.0.lock().unwrap();
    assert!(
        held.blobs
            .contains_key(&format!("sha256:{}", rig.tiny.sha256)),
        "the crate, by its lock digest"
    );
    assert!(
        held.blobs.contains_key(&digest_of(&dependency_archive)),
        "the git dependency, archived at its commit"
    );
    let index: serde_json::Value =
        serde_json::from_slice(held.blobs.get(index_digest).expect("the index")).unwrap();
    assert_eq!(index["crates"][0]["name"], "tiny");
    assert_eq!(index["git"][0]["commit"], rig.dependency_commit.as_str());
    assert_eq!(index["git"][0]["digest"], digest_of(&dependency_archive));
    assert!(
        held.manifests
            .contains_key(&format!("build-dependencies:{}", rig.commit))
    );
}

#[tokio::test]
async fn a_source_with_no_locks_has_no_dependencies() {
    let rig = rig().await;
    let pinned = rig
        .source
        .prepare(&git(&rig, &rig.commit), &public(usize::MAX))
        .await
        .unwrap();
    assert!(pinned.dependencies().is_none());
    assert!(
        !rig.registry
            .0
            .lock()
            .unwrap()
            .manifests
            .keys()
            .any(|k| k.starts_with("build-dependencies:"))
    );
}

