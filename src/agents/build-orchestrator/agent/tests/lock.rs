//! Properties of reading a build's `Cargo.lock` (D1): any lock written as Cargo writes one reads back as exactly what it pins,
//! in any order of its packages; and any one thing in it that is not what Cargo writes, or not pinned, is refused, saying
//! where and never what.

use build_orchestrator::lock::{Crate, Dependencies, GitSource, read, union};
use proptest::prelude::*;

const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";
/// A marker no generated valid value holds, so a problem that echoes a spoiled value is seen.
const MARK: &str = "zqxmarkzqx";

/// One `[[package]]` table, as Cargo writes it.
#[derive(Debug, Clone)]
struct Table {
    name: String,
    version: String,
    source: Option<String>,
    checksum: Option<String>,
    dependencies: Vec<String>,
}

fn render(tables: &[Table]) -> String {
    let mut out = String::from(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n",
    );
    for t in tables {
        out.push_str(&format!(
            "\n[[package]]\nname = \"{}\"\nversion = \"{}\"\n",
            t.name, t.version
        ));
        if let Some(source) = &t.source {
            out.push_str(&format!("source = \"{source}\"\n"));
        }
        if let Some(sum) = &t.checksum {
            out.push_str(&format!("checksum = \"{sum}\"\n"));
        }
        if !t.dependencies.is_empty() {
            out.push_str("dependencies = [\n");
            for d in &t.dependencies {
                out.push_str(&format!(" \"{d}\",\n"));
            }
            out.push_str("]\n");
        }
    }
    out
}

/// A lock's tables and what it pins: crates.io crates, git packages from a few repositories, and workspace members.
fn lock() -> impl Strategy<Value = (Vec<Table>, Dependencies)> {
    let name = "[a-z][a-z0-9_-]{0,10}";
    let version = "[0-9]{1,2}\\.[0-9]{1,2}\\.[0-9]{1,2}(-[a-z0-9.]{1,6})?";
    let deps = proptest::collection::vec("[a-z][a-z0-9_-]{0,8}( [0-9]\\.[0-9])?", 0..3);
    let kind = prop_oneof![
        "[0-9a-f]{64}".prop_map(Some),
        Just(None),
        (
            0usize..3,
            "[0-9a-f]{40}",
            proptest::option::of("(branch|rev|tag)=[a-z0-9]{1,8}")
        )
            .prop_map(|(repo, commit, query)| Some(format!(
                "git {repo} {commit} {}",
                query.unwrap_or_default()
            ))),
    ];
    proptest::collection::vec((name, version, kind, deps), 0..24).prop_map(|items| {
        let mut tables = Vec::new();
        let mut expected = Dependencies::default();
        let mut seen = std::collections::HashSet::new();
        for (name, version, kind, dependencies) in items {
            if !seen.insert((name.clone(), version.clone())) {
                continue;
            }
            let mut table = Table {
                name: name.clone(),
                version: version.clone(),
                source: None,
                checksum: None,
                dependencies,
            };
            match kind {
                Some(k) if k.starts_with("git ") => {
                    let parts: Vec<&str> = k.splitn(4, ' ').collect();
                    let url = format!("https://git{}.example.org/x/y", parts[1]);
                    // One commit per repository, as a lock holds it.
                    let commit = format!("{:0>40}", parts[1]);
                    let _ = parts[2];
                    let locator = if parts[3].is_empty() {
                        url.clone()
                    } else {
                        format!("{url}?{}", parts[3])
                    };
                    table.source = Some(format!("git+{locator}#{commit}"));
                    let source = format!("git+{locator}");
                    match expected.git.iter_mut().find(|g| g.source == source) {
                        Some(g) => g.packages.push((name, version)),
                        None => expected.git.push(GitSource {
                            source,
                            url,
                            commit,
                            packages: vec![(name, version)],
                        }),
                    }
                }
                Some(sum) => {
                    table.source = Some(CRATES_IO.to_string());
                    table.checksum = Some(sum.clone());
                    expected.crates.push(Crate {
                        name,
                        version,
                        sha256: sum,
                    });
                }
                None => {}
            }
            tables.push(table);
        }
        expected.crates.sort();
        for g in &mut expected.git {
            g.packages.sort();
        }
        expected.git.sort();
        (tables, expected)
    })
}

/// One thing a lock may not hold: what it does to a rendered lock, and the words a problem must have.
fn spoil(text: &str, how: usize) -> (String, &'static str) {
    let first_package = text.find("[[package]]").unwrap();
    let (head, body) = text.split_at(first_package);
    let at = |line: &str| {
        format!(
            "{head}{}",
            body.replacen("[[package]]\n", &format!("[[package]]\n{line}\n"), 1)
        )
    };
    match how {
        0 => (at(&format!("{MARK} = \"x\"")), "not a key of a package"),
        1 => (
            at(&format!(
                "source = \"registry+https://{MARK}.example/index\""
            )),
            "",
        ),
        2 => (
            at(&format!("source = \"git+https://{MARK}.example/x\"")),
            "not pinned to a commit",
        ),
        3 => (
            at(&format!("source = \"git+https://{MARK}.example/x#{MARK}\"")),
            "not pinned to a commit",
        ),
        4 => (
            at(&format!(
                "source = \"git+http://{MARK}.example/x#{}\"",
                "a".repeat(40)
            )),
            "not an https address",
        ),
        5 => (
            at(&format!(
                "source = \"git+https://u:{MARK}@x.example/x#{}\"",
                "a".repeat(40)
            )),
            "not an https address",
        ),
        6 => (
            format!(
                "{head}{}",
                body.replacen("name = \"", &format!("name = \"../{MARK}"), 1)
            ),
            "not one",
        ),
        7 => (
            format!(
                "{head}{}",
                body.replacen("name = \"", &format!("name = \"\\\\{MARK}"), 1)
            ),
            "not a plain string",
        ),
        8 => (
            format!("{head}[metadata]\n\"{MARK}\" = \"x\"\n{body}"),
            "line",
        ),
        9 => (text.replacen('\n', "\r\n", 4), "line"),
        10 => (
            at(&format!("dependencies = [\n {MARK},\n]")),
            "not a dependency's name",
        ),
        _ => (at("dependencies = ["), ""),
    }
}

proptest! {
    /// Any lock as Cargo writes it reads back as exactly what it pins, whatever order its packages are in.
    #[test]
    fn a_lock_reads_back_as_what_it_pins_in_any_order((tables, expected) in lock(), seed in any::<u64>()) {
        prop_assert_eq!(read(&render(&tables)), Ok(expected.clone()));
        let mut shuffled = tables.clone();
        let mut state = seed;
        for i in (1..shuffled.len()).rev() {
            state = state.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
            shuffled.swap(i, (state >> 33) as usize % (i + 1));
        }
        prop_assert_eq!(read(&render(&shuffled)), Ok(expected));
    }

    /// Any one thing not as Cargo writes it, or not pinned, is refused, and no problem repeats what the lock said.
    #[test]
    fn a_spoiled_lock_is_refused_and_never_echoed((tables, _) in lock().prop_filter("one package at least", |(t, _)| !t.is_empty()), how in 0usize..12) {
        let (spoiled, words) = spoil(&render(&tables), how);
        let problems = read(&spoiled).unwrap_err();
        prop_assert!(problems.iter().any(|p| p.contains(words)), "{} in {:?}", words, problems);
        prop_assert!(!problems.iter().any(|p| p.contains(MARK)), "{:?}", problems);
    }

    /// The dependencies of several locks: the same whatever order the locks come in, holding everything each pins, and
    /// nothing else; and a lock's own dependencies are their own union.
    #[test]
    fn the_union_of_locks_is_every_part_and_no_more(parts in proptest::collection::vec(lock().prop_map(|(_, d)| d), 0..4)) {
        let all = union(parts.clone());
        let mut reversed = parts.clone();
        reversed.reverse();
        prop_assert_eq!(&union(reversed), &all);
        for part in &parts {
            prop_assert_eq!(&union(vec![part.clone()]), part);
            for c in &part.crates {
                prop_assert!(all.crates.contains(c));
            }
            for g in &part.git {
                let held = all.git.iter().find(|h| h.source == g.source && h.commit == g.commit).unwrap();
                prop_assert!(g.packages.iter().all(|p| held.packages.contains(p)));
            }
        }
        for c in &all.crates {
            prop_assert!(parts.iter().any(|p| p.crates.contains(c)));
        }
        for g in &all.git {
            for p in &g.packages {
                prop_assert!(parts.iter().any(|part| part.git.iter().any(|h| h.source == g.source && h.commit == g.commit && h.packages.contains(p))));
            }
        }
    }

    /// A crates.io package with no checksum, or one that is not a sha256, is refused.
    #[test]
    fn a_crate_not_pinned_by_its_sha256_is_refused(name in "[a-z][a-z0-9_-]{0,10}", sum in proptest::option::of("[0-9A-Fa-f]{0,63}")) {
        let table = Table { name, version: "1.0.0".into(), source: Some(CRATES_IO.into()), checksum: sum, dependencies: vec![] };
        let problems = read(&render(&[table])).unwrap_err();
        prop_assert!(problems.iter().any(|p| p.contains("checksum")), "{:?}", problems);
    }
}

#[test]
fn a_lock_past_its_bound_is_refused_unread() {
    let huge = "#".repeat(build_orchestrator::lock::MAX_LOCK + 1);
    assert!(read(&huge).unwrap_err()[0].contains("larger than"));
}
